# 기본위치: (1,1) = (X,Y)
# R이 주어지면 (1,2)로 가게 되고 그 후 D가 주어지면 (2,2)로 가게 된다.
# 가로 = Y, 세로 = X
# 일반적으로 생각하는 X(가로) Y(세로)가 아닌 문제의 뜻을 파악했어야함