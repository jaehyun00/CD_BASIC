#    dx = [-1, 0, 1, 0], dy = [0, 1, 0, -1] 사실 이게 x, y가 바뀐거 같긴한데
#    x, y 별 이동 가능한 수를 정의 해놓는 개념 놓침
# 2. 회전한 이후 정면에 가보지 않은 칸이 없거나 바다인 경우를 구현하지 않음
# 3. 네 방향 모두 갈 수 없는 경우 뒤로 갈 수 있다면 이동하는 부분, 뒤가 바다로 막혀 있는 부분 구현하지 않음
