# DFS 예제 풀어보기
#

# -------------------------------------------------------------------
# 개인 풀이
# -------------------------------------------------------------------
graph = [
    [],
    [2,3,8],
    [1,7],
    [1,4,5],
    [3,5],
    [3,4],
    [7],
    [2,6,8],
    [1,7]
]

# DSF 구현 해보기
def dfs (graph, v, visited):
    # 방문 기록 세팅
    visited[v] = True

    # 현재 노드 출력
    print(v, end='')

    # print(f'graph[v]: {graph[v]}')

    # 현재 노드에 이어진 다른 노드 탐색
    for g in graph[v]:
        # print(f'visited[g]: {visited[g]}')
        if not visited[g]:
            dfs(graph, g, visited)

# 방문 기록
visited = [False] * 9

# DFS 함수 호출
dfs(graph, 1, visited)


